export async function seedRbac(prisma: PrismaClient): Promise<void> {
  console.log("🌱 Seeding RBAC (roles, permissions, role-permissions)...");

  // 1. Upsert roles
  let roleCount = 0;
  for (const roleKey of Object.values(ROLES)) {
    const meta = ROLE_METADATA[roleKey];
    await prisma.role.upsert({
      where: { key: roleKey },
      update: {
        name: meta.name,
        description: meta.description,
        isSystem: meta.isSystem,
      },
      create: {
        key: roleKey,
        name: meta.name,
        description: meta.description,
        isSystem: meta.isSystem,
      },
    });
    roleCount++;
  }
  console.log(`  ✓ Roles upserted: ${roleCount}`);

  // 2. Upsert permissions
  let permCount = 0;
  for (const perm of PERMISSION_SEEDS) {
    await prisma.permission.upsert({
      where: { key: perm.key },
      update: {
        category: perm.category,
        description: perm.description,
      },
      create: {
        key: perm.key,
        category: perm.category,
        description: perm.description,
      },
    });
    permCount++;
  }
  console.log(`  ✓ Permissions upserted: ${permCount}`);

  // 3. Load all roles and permissions into maps for fast lookup
  const allRoles = await prisma.role.findMany();
  const allPerms = await prisma.permission.findMany();

  const roleByKey = new Map(allRoles.map((r) => [r.key, r]));
  const permByKey = new Map(allPerms.map((p) => [p.key, p]));

  // 4. Upsert role-permission links
  let linkCount = 0;

  for (const [roleKey, permKeys] of Object.entries(ROLE_PERMISSIONS) as [
    RoleKey,
    Permission[],
  ][]) {
    const role = roleByKey.get(roleKey);
    if (!role) {
      console.warn(`  ⚠ Role not found: ${roleKey} — skipping`);
      continue;
    }

    for (const permKey of permKeys) {
      const perm = permByKey.get(permKey);
      if (!perm) {
        console.warn(`  ⚠ Permission not found: ${permKey} — skipping`);
        continue;
      }

      await prisma.rolePermission.upsert({
        where: {
          roleId_permissionId: {
            roleId: role.id,
            permissionId: perm.id,
          },
        },
        update: {},
        create: {
          roleId: role.id,
          permissionId: perm.id,
        },
      });
      linkCount++;
    }
  }
  console.log(`  ✓ Role-permission links upserted: ${linkCount}`);

  console.log("✅ RBAC seeding complete.\n");
}

