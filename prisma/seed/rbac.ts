export function getRbacSummary() {
  const summary = Object.entries(ROLE_PERMISSIONS).map(
    ([roleKey, perms]) => ({
      roleKey,
      permissionCount: perms.length,
    }),
  );

  const total = summary.reduce((acc, r) => acc + r.permissionCount, 0);

  return {
    roleCount: Object.keys(ROLES).length,
    permissionCount: PERMISSION_SEEDS.length,
    totalRolePermissionLinks: total,
    byRole: summary,
  };
}